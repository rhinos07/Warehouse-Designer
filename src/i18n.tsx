export const TEXTS: Record<Lang, Record<string, string>> = { de, en };

function initial(): Lang {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "de" || saved === "en") return saved;
  } catch {
    // storage blocked: fall back to the browser language
  }
  return typeof navigator !== "undefined" && /^en\b/i.test(navigator.language) ? "en" : "de";
}

let current: Lang = typeof window === "undefined" ? "de" : initial();
const listeners = new Set<() => void>();
if (typeof document !== "undefined") document.documentElement.lang = current;

export const getLang = (): Lang => current;

export function setLang(lang: Lang) {
  current = lang;
  try {
    localStorage.setItem("lang", lang);
  } catch {
    // storage blocked: the choice lasts for this page only
  }
  document.documentElement.lang = lang;
  listeners.forEach((listener) => listener());
}

/** The current language; a component using it re-renders when it changes. */
export function useLang(): Lang {
  return useSyncExternalStore(
    (listener) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    getLang,
    getLang,
  );
}

/** The text for a key in the current language, with {name} placeholders filled in. */
export function t(key: string, params: Record<string, string | number> = {}): string {
  const text = TEXTS[current][key] ?? TEXTS.de[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (whole, name) => (name in params ? String(params[name]) : whole));
}

/** A counted text: key_one for 1, key_other otherwise, with {n}. */
export const tn = (key: string, n: number, params: Record<string, string | number> = {}) =>
  t(`${key}_${n === 1 ? "one" : "other"}`, { ...params, n });

/** A label for a value, e.g. tl("kind", "door") → Tor / Door; the value itself if there is none. */
export function tl(prefix: string, value: string): string {
  const key = `${prefix}.${value}`;
  return key in TEXTS[current] || key in TEXTS.de ? t(key) : value;
}

/** DE | EN, at the top of the page. */
export function LanguageSwitch() {
  const lang = useLang();
  return (
    <div className="lang-switch" role="group" aria-label={t("lang.label")}>
      {(["de", "en"] as Lang[]).map((l) => (
        <button key={l} type="button" aria-pressed={lang === l} className={lang === l ? "active" : "secondary"} onClick={() => setLang(l)}>
          {l.toUpperCase()}
        </button>
      ))}
    </div>
  );
}
